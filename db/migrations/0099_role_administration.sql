-- Revue de sécurité du 14 novembre 2026, A1 (critique) : l'API d'administration avait le même rôle et le même mot de passe
-- que l'API publique, et les fonctions d'administration croient l'identifiant qu'on leur passe. Un site public compromis
-- pouvait donc agir en super-administrateur.
-- Désormais : rôle « argos_administration » (hérite du site, argos_app, pour tout le reste), seul autorisé à exécuter les
-- fonctions d'administration ; l'API d'administration s'y connecte avec son propre mot de passe (rôle de connexion
-- argos_api_admin, secret pg-api-admin). L'API publique ne peut plus les appeler.
-- Les fonctions d'administration ajoutées plus tard doivent être accordées à argos_administration, jamais à argos_app.

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'argos_administration') THEN
        CREATE ROLE argos_administration NOLOGIN;
    END IF;
END $$;
GRANT argos_app TO argos_administration;
-- Comme pour les autres rôles (0001) : le propriétaire peut l'endosser (tests), sans en hériter les droits.
GRANT argos_administration TO CURRENT_USER WITH INHERIT FALSE, SET TRUE;

